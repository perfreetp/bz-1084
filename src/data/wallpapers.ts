import type { Wallpaper } from "@/types";

const createWallpaper = (
  id: string,
  title: string,
  description: string,
  imageUrl: string,
  categoryId: string,
  authorId: string,
  aspectRatio: Wallpaper["aspectRatio"],
  colors: string[],
  tags: string[],
  daysAgo: number,
  stats: { views: number; downloads: number; favorites: number }
): Wallpaper => {
  const date = new Date();
  date.setDate(date.getDate() - daysAgo);
  return {
    id,
    title,
    description,
    imageUrl,
    thumbnailUrl: imageUrl,
    resolutions: [
      { name: "4K UHD", width: 3840, height: 2160, url: imageUrl, size: "8.5 MB" },
      { name: "2K QHD", width: 2560, height: 1440, url: imageUrl, size: "4.2 MB" },
      { name: "1080P FHD", width: 1920, height: 1080, url: imageUrl, size: "2.1 MB" },
    ],
    aspectRatio,
    colors,
    tags,
    categoryId,
    authorId,
    uploadedAt: date.toISOString(),
    copyright: {
      type: "cc",
      license: "CC BY-NC-SA 4.0",
      attribution: "需注明原作者",
      watermark: false,
    },
    ...stats,
  };
};

